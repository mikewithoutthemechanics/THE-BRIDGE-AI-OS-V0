#!/usr/bin/env node
/**
 * gen-admin-groups.mjs — Codegen for MasterAdmin.tsx
 *
 * Reads public/nav-routes.js (single source of truth), evaluates its IIFE in
 * a stubbed `window` context, extracts ADMIN_GROUPS, and emits a typed TS
 * module at src/generated/admin-groups.ts consumed by MasterAdmin.tsx.
 *
 * Runs as `prebuild` so `vite build` always sees fresh output. Also safe to
 * run manually: `node scripts/gen-admin-groups.mjs`.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const __dirname = dirname(fileURLToPath(import.meta.url));
const SRC = resolve(__dirname, '../../public/nav-routes.js');
const OUT = resolve(__dirname, '../src/generated/admin-groups.ts');

const source = readFileSync(SRC, 'utf8');

// Stub a minimal window so the IIFE can assign BridgeNavRoutes.
const sandbox = { window: {} };
vm.createContext(sandbox);
vm.runInContext(source, sandbox, { filename: 'nav-routes.js' });

const reg = sandbox.window.BridgeNavRoutes;
if (!reg || !Array.isArray(reg.ADMIN_GROUPS)) {
  console.error('[gen-admin-groups] BridgeNavRoutes.ADMIN_GROUPS missing from nav-routes.js');
  process.exit(1);
}

const banner = `// AUTO-GENERATED by frontend/scripts/gen-admin-groups.mjs — DO NOT EDIT.
// Source of truth: public/nav-routes.js (BridgeNavRoutes.ADMIN_GROUPS).
// Regenerate with: npm run gen:admin-groups (runs automatically on prebuild).
`;

const body = `
export type Role = 'user' | 'admin' | 'superadmin' | null;

export interface AdminItem {
  label: string;
  href: string;
  desc?: string;
  role?: Role;
}

export interface AdminGroup {
  id: string;
  title: string;
  desc: string;
  role: Role;
  items: AdminItem[];
}

export const ADMIN_GROUPS: readonly AdminGroup[] = ${JSON.stringify(reg.ADMIN_GROUPS, null, 2)} as const;

export const ROLE_ORDER: readonly Role[] = ${JSON.stringify(reg.ROLE_ORDER)} as const;

export const REGISTRY_VERSION = ${JSON.stringify(reg.version || 'unknown')};
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, banner + body, 'utf8');

console.log(`[gen-admin-groups] Wrote ${reg.ADMIN_GROUPS.length} groups (${reg.ADMIN_GROUPS.reduce((n, g) => n + (g.items?.length || 0), 0)} items) → ${OUT}`);
